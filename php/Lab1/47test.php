<?php
$count = 0;      // Счетчик четных чисел
$sum = 0;        // Сумма четных чисел
$number = 1;     // Текущее число

// Цикл с постусловием (do-while)
do {
    if ($number % 2 == 0) {
        $sum += $number;
        $count++;
    }
    $number++;
} while ($count < 20);

echo "Сумма первых 20 четных членов натурального ряда: " . $sum;
?>