<?php
$count = 0;      // Счетчик нечетных чисел
$sum = 0;        // Сумма нечетных чисел
$number = 1;     // Текущее число

// Цикл с предусловием (while)
while ($count < 20) {
    $sum += $number;
    $number += 2;    // Переходим к следующему нечетному числу
    $count++;
}

echo "Сумма первых 20 нечетных членов натурального ряда: " . $sum;
?>