<?php
// Создаем массив
$arr = [2, 5, 3, 9];

// Умножаем первый элемент на второй, третий на четвертый
$multiply1 = $arr[0] * $arr[1];  // 2 * 5 = 10
$multiply2 = $arr[2] * $arr[3];  // 3 * 9 = 27

// Складываем результаты
$result = $multiply1 + $multiply2;  // 10 + 27 = 37

// Выводим результат
echo "Результат: " . $result . "\n";

// Или более компактно:
$result2 = ($arr[0] * $arr[1]) + ($arr[2] * $arr[3]);
echo "Результат (компактный вариант): " . $result2 . "\n";

// Для проверки можно вывести сам массив
echo "\nМассив \$arr:\n";
print_r($arr);
?>