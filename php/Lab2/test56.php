<?php
// Функция, которая возвращает день недели на русском языке
function getDayOfWeek($dayNumber) {
    // Массив с днями недели
    $days = [
        1 => 'понедельник',
        2 => 'вторник',
        3 => 'среда',
        4 => 'четверг',
        5 => 'пятница',
        6 => 'суббота',
        7 => 'воскресенье'
    ];
    
    // Проверяем, что число в диапазоне 1-7
    if ($dayNumber >= 1 && $dayNumber <= 7) {
        return $days[$dayNumber];
    } else {
        return "Ошибка: число должно быть от 1 до 7";
    }
}

// Примеры использования
echo getDayOfWeek(1) . "\n";   // понедельник
echo getDayOfWeek(3) . "\n";   // среда
echo getDayOfWeek(7) . "\n";   // воскресенье
echo getDayOfWeek(8) . "\n";   // Ошибка
?>