<?php
// Исходный массив
$arr = ['3'=>'a', '1'=>'c', '2'=>'e', '4'=>'b'];

echo "Исходный массив:\n";
print_r($arr);
echo "\n";

// 1. sort() - сортировка по значениям (по возрастанию), ключи сбрасываются
$arr1 = $arr;
sort($arr1);
echo "1. sort() - сортировка по значениям по возрастанию:\n";
print_r($arr1);

// 2. rsort() - сортировка по значениям (по убыванию), ключи сбрасываются
$arr2 = $arr;
rsort($arr2);
echo "\n2. rsort() - сортировка по значениям по убыванию:\n";
print_r($arr2);

// 3. asort() - сортировка по значениям с сохранением ключей (по возрастанию)
$arr3 = $arr;
asort($arr3);
echo "\n3. asort() - сортировка по значениям с сохранением ключей (по возрастанию):\n";
print_r($arr3);

// 4. arsort() - сортировка по значениям с сохранением ключей (по убыванию)
$arr4 = $arr;
arsort($arr4);
echo "\n4. arsort() - сортировка по значениям с сохранением ключей (по убыванию):\n";
print_r($arr4);

// 5. ksort() - сортировка по ключам (по возрастанию)
$arr5 = $arr;
ksort($arr5);
echo "\n5. ksort() - сортировка по ключам (по возрастанию):\n";
print_r($arr5);

// 6. krsort() - сортировка по ключам (по убыванию)
$arr6 = $arr;
krsort($arr6);
echo "\n6. krsort() - сортировка по ключам (по убыванию):\n";
print_r($arr6);

// 7. natsort() - естественная сортировка по значениям с сохранением ключей
$arr7 = $arr;
natsort($arr7);
echo "\n7. natsort() - естественная сортировка по значениям с сохранением ключей:\n";
print_r($arr7);

// 8. natcasesort() - естественная сортировка без учета регистра
$arr8 = $arr;
natcasesort($arr8);
echo "\n8. natcasesort() - естественная сортировка без учета регистра:\n";
print_r($arr8);
?>